#pragma once
#include <SFML/Graphics.hpp>
#include <SFML/Audio.hpp>
#include <vector>
#include <string>
#include <random>

using namespace sf;
using namespace std;

// ??? Типы карт ???????????????????????????????????????????????????????????????
enum class CardType { Attack, Defend, Buff, Debuff };

// ??? Типы врагов ?????????????????????????????????????????????????????????????
enum class EnemyType { Tutorial, Brute, Shaman, Duelist, Assassin, Boss };

// ??? Данные карты (только числа и текст, без графики) ????????????????????????
struct CardData
{
    wstring  name;
    wstring  description;
    CardType type;
    int      energyCost;  // стоимость в очках энергии
    int      value;       // урон / блок / величина эффекта
    int      effectType;  // уточняет поведение карты (0 = по умолчанию, см. Battle.cpp)
};

// ??? Карта в руке (данные + SFML-визуал) ?????????????????????????????????????
struct HandCard
{
    CardData       data;
    RectangleShape body;
    Text* nameText;
    Text* descriptionText;
    Text* costText;
    bool           dragging;       // зарезервировано (перетаскивание не реализовано)
    bool           mouse_hovered;
    Vector2f       originalPosition;
};

// ??? Намерение врага на текущий ход ??????????????????????????????????????????
enum class EnemyIntent { Attack, Defend, Buff };

// ?????????????????????????????????????????????????????????????????????????????
class Battle
{
    // ?? Внутренние вспомогательные методы ????????????????????????????????????????
private:
    void buildDeck();                          // создаёт стартовую колоду из базовых карт
    void drawCards(int count);                 // берёт count карт из колоды в руку
    void enemyTurnAction();                    // выполняет действие врага
    void generateNextEnemyIntent();            // выбирает следующее намерение врага
    void showMessage(const wstring& msg);      // показывает всплывающее сообщение

    // ?? Визуальные объекты боя ???????????????????????????????????????????????????
    Font* battleFont;
    Text* heroHPText;
    Text* enemyHPText;
    Text* heroBlockText;
    Text* enemyBlockText;
    Text* heroStrengthText;  // зелёный: бафф силы героя
    Text* enemyPoisonText;   // фиолетовый: яд на враге
    Text* enemyWeakenText;   // фиолетовый: ослабление врага
    Text* energyText;
    Text* enemyIntentText;
    Text* endTurnText;
    Text* messageText;
    Text* enemyNameText;

    SoundBuffer    heroFaile;
    Sound* deathOfHero;       // звук смерти героя

    wstring        resultStr;         // строка итога боя ("ВЫ ПОБЕДИЛИ" / "ВЫ ПОГИБЛИ")

    RectangleShape battleBG;
    Texture        battleBGimage;

    // HP-бары (передний план + фон)
    RectangleShape heroHPbar, heroHPbarBg;
    RectangleShape enemyHPbar, enemyHPbarBg;

    // Энергия и кнопка конца хода
    CircleShape    energyBar;
    RectangleShape endTurnButton;

    // ?? Состояние врага ??????????????????????????????????????????????????????????
    EnemyIntent currentIntent;
    EnemyType   currentEnemyType;

    int intentValue;       // величина намерения (урон / блок / бонус)
    int heroStrength;      // бонус к атаке героя (длится несколько ходов)
    int enemyStrength;     // накопленный бонус атаки врага
    int enemyDefenseBonus; // бонус к блоку врага
    int enemyRegeneration; // регенерация HP врага за ход
    int enemyHealing;      // разовое лечение врага (резерв)
    int buff;              // код специального действия врага (0-5)
    int turnCount;         // счётчик ходов врага (для паттернов)
    bool enemyDieing;      // флаг начала анимации смерти (резерв)

    // ?? Текстуры карт ????????????????????????????????????????????????????????????
    Texture attackCardTex;
    Texture defendCardTex;
    Texture buffCardTex;
    Texture debuffCardTex;

    // ?? Служебные флаги ??????????????????????????????????????????????????????????
    bool  mouseWasClicked;    // предыдущее состояние ЛКМ (для edge-detect клика)
    bool  enemyTurnPending;   // враг ещё не сходил в этом переходе
    float messageTtl;         // оставшееся время показа сообщения (секунды)
    bool  deathSoundPlayed;   // звук смерти уже проигран (играть только раз)

    // ?? Механики стана (Оковы) ???????????????????????????????????????????????????
    bool heroStunnedAttack;    // герой не может атаковать в этот ход
    bool heroStunnedDefend;    // герой не может защищаться в этот ход
    bool enemyAppliesStunNext; // враг наложит Оковы в начале следующего хода игрока

    // ?? Карта "Предсказуемость" — панель выбора намерения врага ??????????????????
    bool        showForesightPanel;   // открыта ли панель
    int         foresightCardIndex;   // индекс карты в руке (-1 = нет активной карты)
    EnemyIntent foresightChosenIntent;
    int         foresightChosenBuff;

    RectangleShape foresightPanelBg;
    RectangleShape foresightOptionAttack;
    RectangleShape foresightOptionDefend;
    RectangleShape foresightOptionBuff;
    RectangleShape foresightOptionDebuff;
    Text* foresightTitleText;
    Text* foresightAttackText;
    Text* foresightDefendText;
    Text* foresightBuffText;
    Text* foresightDebuffText;

    // ?? Открытые данные (читаются из Game) ???????????????????????????????????????
public:
    // HP и блок
    int heroHP, heroMaxHP, heroBlock;
    int enemyHP, enemyMaxHP, enemyBlock;

    // Энергия
    int energy, maxEnergy;

    // Бонусы и дебаффы
    int heroDefenseBonus;  // бонус блока героя на этот ход
    int echo;              // оставшихся ходов действия silы
    int heroIntentBonus;   // одноразовый бонус к следующей атаке

    int buffStandartBonus; // резерв: бонус мгновенного щита
    int poison;            // стак яда на враге (урон/ход)
    int debuffStandart;    // ослабление врага (снижает его урон)
    int heroWeaken;        // бессилие героя (снижает его урон)
    int heroPoison;        // яд на герое (урон в начале хода игрока)

    // Состояние боя
    bool playerTurn;
    bool battleOver;
    bool playerWon;
    bool extraTurnGranted; // флаг дополнительного хода (от карты "Адреналин")

    // Колода, сброс, рука
    vector<CardData> deck;
    vector<CardData> discardPile;
    vector<HandCard> hand;

    // ?? Жизненный цикл ????????????????????????????????????????????????????????
    Battle();
    ~Battle();

    void initBattle(Font* font); // инициализирует визуальные объекты (вызывается один раз)

    // Запускает новый бой: передаёт HP героя, индекс узла карты и доп. карты игрока
    void startBattle(int hHP, int hMaxHP, int nodeIndex, vector<CardData>& extraCards);

    void update(Vector2f mousePos, bool mouseDown, float dt); // логика каждый кадр
    void battleBGrender(RenderWindow* window);                // рисует фон боя
    void render(RenderWindow* window, bool eGame);            // рисует весь UI боя

    EnemyType getEnemyType() const { return currentEnemyType; }
};
